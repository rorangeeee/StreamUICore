import { cp, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
const directory = process.argv[2];
if (!directory) throw Error('Expected isolated user directory.');
await mkdir(directory, {recursive:true});
await cp(path.resolve('tests/fixtures/scenes'),path.join(directory,'scenes'),{recursive:true});
await cp(path.resolve('tests/fixtures/scenes/live'),path.join(directory,'scenes/rehearsal'),{recursive:true});
const scene=(id,name,folder=id)=>({id,name,entry:'scenes/'+folder+'/index.html',width:1920,height:1080,transition:'scenes/'+folder+'/fade.js',settingsPage:'scenes/'+folder+'/settings.html'});
await writeFile(path.join(directory,'core-settings.json'),JSON.stringify({formatVersion:2,scenes:[{...scene('live','直播'),defaults:'scenes/live/defaults.json'},scene('second','第二场景','away'),scene('rehearsal','排练')],selectedSceneId:'live',enabledPlugins:[]},null,2));
await writeFile(path.join(directory,'scenes/live/defaults.json'),JSON.stringify({title:'Author title',layout:{x:.85}}));
